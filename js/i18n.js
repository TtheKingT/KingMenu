const savedLanguage = localStorage.getItem('kingLang');
const browserLanguage = navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'es';
export let currentLang = savedLanguage === 'es' || savedLanguage === 'en' ? savedLanguage : browserLanguage;
document.documentElement.lang = currentLang;

export function t(key) {
    if (translations[currentLang] && translations[currentLang][key]) {
        return translations[currentLang][key];
    }
    return translations.es[key] || key;
}

export function formatPrice(price) {
    const num = Number(price) || 0;
    return new Intl.NumberFormat('es-CO', {
        style: 'currency',
        currency: 'COP',
        minimumFractionDigits: 0,
        maximumFractionDigits: 0
    }).format(num);
}

export function getCatLocalized(catName) {
    if (!catName) return '';
    if (currentLang !== 'en') return catName;
    const dict = {
        'Todos': t('cat_all'),
        'Entradas': t('cat_apps'),
        'Fuertes': t('cat_mains'),
        'Postres': t('cat_dess'),
        'Bebidas': t('cat_bevs'),
        'Vinos y Cocteles': t('cat_wines'),
        'Picadas': t('cat_picadas')
    };
    return dict[catName] || catName;
}

/**
 * Universal bilingual field helper.
 * Usage: getLocalizedField(item, 'description')
 *   → returns item.descriptionEn if currentLang === 'en' and field is non-empty,
 *     otherwise falls back to item.description (Spanish).
 *
 * @param {Object} item - Product or dish object.
 * @param {string} field - Base property name (e.g. 'name', 'description', 'ingredients', 'category').
 * @returns {string}
 */
export function getLocalizedField(item, field) {
    if (!item) return '';
    const isEn = currentLang === 'en';
    const enField = field + 'En'; // e.g. 'name' -> 'nameEn'
    if (isEn && item[enField] && String(item[enField]).trim() !== '') {
        return String(item[enField]);
    }
    return item[field] ? String(item[field]) : '';
}

export function getProductLocalized(product) {
    if (!product) return {};
    const isEn = currentLang === 'en';
    const name = getLocalizedField(product, 'name') || (isEn ? 'Imperial Dish' : 'Platillo Imperial');
    const description = getLocalizedField(product, 'description') || (isEn ? 'Imperial culinary creation.' : 'Creación culinaria imperial.');
    const category = isEn && product.categoryEn && product.categoryEn.trim() !== ''
        ? product.categoryEn
        : getCatLocalized(product.category || 'Entradas');
    const ingredients = getLocalizedField(product, 'ingredients');
    const fallbackImage = 'https://images.unsplash.com/photo-1546069901-ba9599a7e63c?auto=format&fit=crop&w=800';
    const imageRecords = Array.isArray(product.imageUrls)
        ? product.imageUrls.map(image => typeof image === 'string'
            ? { url: image, srcset: '', width: 800, height: 600 }
            : {
                url: image?.url || image?.cropped || '',
                srcset: image?.srcset || '',
                width: Number(image?.width) || 800,
                height: Number(image?.height) || 600
            })
            .filter(image => image.url)
        : [];
    const imageUrl = typeof product.imageUrl === 'string'
        ? product.imageUrl
        : product.imageUrl?.url || product.imageUrl?.cropped || imageRecords[0]?.url || fallbackImage;
    const imageUrls = imageRecords.length > 0 ? imageRecords.map(image => image.url) : [imageUrl];
    const imageSrcsets = imageRecords.length > 0 ? imageRecords.map(image => image.srcset) : [''];

    return {
        id: product.id,
        name,
        description,
        category,
        ingredients,
        price: product.price || 0,
        imageUrl,
        imageUrls,
        imageSrcsets,
        imageWidths: imageRecords.map(image => image.width),
        imageHeights: imageRecords.map(image => image.height),
        model3dUrl: product.model3dUrl || ''
    };
}

export function setLanguage(lang) {
    if (lang !== 'es' && lang !== 'en') return;
    currentLang = lang;
    localStorage.setItem('kingLang', currentLang);
    document.documentElement.lang = currentLang;
}
